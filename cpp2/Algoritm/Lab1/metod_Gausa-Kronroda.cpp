using namespace std;

// Узлы Кронрода на [-1,1] (15 точек, симметричны)
const double x_kronrod[] = {
    -0.9914553711208126, -0.9491079123427585, -0.8648644233597691,
    -0.7415311855993944, -0.5860872354676911, -0.4058451513773972,
    -0.2077849550078985,  0.0000000000000000,  0.2077849550078985,
     0.4058451513773972,  0.5860872354676911,  0.7415311855993944,
     0.8648644233597691,  0.9491079123427585,  0.9914553711208126
};

// Веса Кронрода (15)
const double w_kronrod[] = {
    0.02293532201052922, 0.06309209262997855, 0.1047900103222502,
    0.1406532597155259,  0.1690047266392679,  0.1903505780647854,
    0.2044329400752989,  0.2094821410847278,  0.2044329400752989,
    0.1903505780647854,  0.1690047266392679,  0.1406532597155259,
    0.1047900103222502,  0.06309209262997855, 0.02293532201052922
};

// Веса Гаусса для вложенного 7-точечного правила
const double w_gauss[] = {
    0.1294849661688697, 0.2797053914892767, 0.3818300505051889,
    0.4179591836734694, 0.3818300505051889, 0.2797053914892767,
    0.1294849661688697
};

// Индексы узлов Гаусса в массиве узлов Кронрода (7 точек)
const int gauss_indices[] = {0, 2, 4, 6, 8, 10, 12};

/**
 * Вычисляет интеграл от f на [a,b] методом Гаусса-Кронрода (15 точек)
 * и возвращает оценку погрешности через error.
 */
double gauss_kronrod(const function<double(double)>& f, double a, double b, double& error) {
    double jacobian = (b - a) / 2.0;          // множитель преобразования
    double I_kronrod = 0.0;
    double I_gauss = 0.0;

    // Сумма Кронрода по всем 15 точкам
    for (int i = 0; i < 15; ++i) {
        double x = 0.5 * (b - a) * x_kronrod[i] + 0.5 * (b + a); // преобразование на [a,b]
        I_kronrod += w_kronrod[i] * f(x);
    }

    // Сумма Гаусса по 7 точкам (используем соответствующие индексы)
    for (int idx = 0; idx < 7; ++idx) {
        int i = gauss_indices[idx];
        double x = 0.5 * (b - a) * x_kronrod[i] + 0.5 * (b + a);
        I_gauss += w_gauss[idx] * f(x);
    }

    I_kronrod *= jacobian;
    I_gauss   *= jacobian;

    error = fabs(I_kronrod - I_gauss);   // оценка погрешности
    return I_kronrod;                     // возвращаем более точное значение
}

// Пример использования
int main() {
    // Интегрируем функцию
    auto f = [](double x) {
        return cos(3*x)/(1+0.7*cos(x));
    };

    double a, b;
    cout << "Введите начало интервала: ";
    cin >> a;
    cout << "Введите конец интервала(через точку): ";
    cin >> b;
    double error;

    double result = gauss_kronrod(f, a, b, error); // error передается как ссылка

    cout << fixed << setprecision(12);
    cout << "Интеграл: " << result << endl;
    cout << "Оценка погрешности: " << scientific << error << endl;

    return 0;
}