    public MainWindow()
    {
        InitializeComponent();
    }

    public static int NOD(int a, int b) // метод Евклида
    {
        if (a == 0) return b;
        while (b != 0)
        {
            if (a > b)
            {
                a -= b;
            }
            else
            {
                b -= a;
            }
        }
        return a;
    }
}

