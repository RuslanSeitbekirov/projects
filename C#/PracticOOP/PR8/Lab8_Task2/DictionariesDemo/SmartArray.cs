using System;

namespace DictionariesDemo
{
    // =========================================================================
    //  Пункт 2. "Умный массив" с помощью индексатора.
    //
    //  Обычный массив при обращении к несуществующему элементу (array[100]
    //  при длине 5) выбрасывает IndexOutOfRangeException, и программа падает.
    //  А ещё в int[] можно записать любое число, в том числе отрицательное.
    //
    //  Задание: сделать массив, который
    //    - не позволяет выйти за свои границы;
    //    - не принимает отрицательные числа.
    //
    //  ИНДЕКСАТОР — это особое свойство, благодаря которому с объектом класса
    //  можно работать через квадратные скобки, как с массивом: smart[2] = 7.
    //  Пишется он как свойство с именем this:
    //
    //      public int this[int index]
    //      {
    //          get { ... }   // выполняется при чтении:  x = smart[2];
    //          set { ... }   // выполняется при записи:  smart[2] = 7;
    //      }
    //
    //  Главное: внутри get и set можно написать ЛЮБЫЕ проверки. Обычный массив
    //  так не умеет, а наш класс — умеет, поэтому он и "умный".
    //
    //  Я решил, что при ошибке мой массив не будет "ронять" программу:
    //  неправильная запись просто не выполняется, неправильное чтение
    //  возвращает 0, а текст ошибки сохраняется в свойстве LastError.
    // =========================================================================

    public class SmartArray
    {
        // Настоящий массив спрятан внутри (private), снаружи к нему
        // можно добраться только через индексатор с проверками.
        private readonly int[] data;

        /// <summary>Создаёт массив заданного размера (заполнен нулями).</summary>
        public SmartArray(int size)
        {
            if (size < 0)
            {
                size = 0;   // отрицательного размера не бывает
            }
            data = new int[size];
        }

        /// <summary>Длина массива.</summary>
        public int Length
        {
            get { return data.Length; }
        }

        /// <summary>
        /// Описание последней ошибки или null, если последнее обращение
        /// прошло успешно.
        /// </summary>
        public string LastError { get; private set; }

        /// <summary>Проверяет, что индекс попадает в границы массива.</summary>
        private bool IsValidIndex(int index)
        {
            return index >= 0 && index < data.Length;
        }

        /// <summary>Индексатор: доступ к элементам через [ ].</summary>
        public int this[int index]
        {
            get
            {
                if (!IsValidIndex(index))
                {
                    LastError = "чтение: индекс " + index + " вне границ 0.." + (data.Length - 1);
                    return 0;   // возвращаем безопасное значение вместо падения
                }

                LastError = null;
                return data[index];
            }
            set
            {
                // value — число, которое пытаются записать
                if (!IsValidIndex(index))
                {
                    LastError = "запись: индекс " + index + " вне границ 0.." + (data.Length - 1);
                    return;     // ничего не записываем
                }

                if (value < 0)
                {
                    LastError = "запись: отрицательное число " + value + " не принимается";
                    return;     // старое значение остаётся на месте
                }

                LastError = null;
                data[index] = value;
            }
        }

        /// <summary>Все элементы одной строкой.</summary>
        public override string ToString()
        {
            return "[" + string.Join(", ", data) + "]";
        }
    }
}
