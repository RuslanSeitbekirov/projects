3. Поставьте на первое место блок catch с общим исключением. Что произойдет?
Программа не скомпилируется. Компилятор не допускает специфичные catch после общего: он выдаёт ошибку CS1017 для catch без параметров 
или CS0160 для catch (Exception). Правило такое: блоки catch проверяются сверху вниз, срабатывает первый подходящий, поэтому порядок 
должен быть от частных исключений к общим. Общий блок всегда идёт последним.

4. Можно убрать все внутренние блоки catch? Можно ли оставить только блок Try?
Убрать все внутренние catch можно. Остаётся try … finally. Тогда исключение сначала вызывает finally, а затем уходит выше и обрабатывается 
внешним catch. Оставить только try нельзя: после try обязательно должен идти хотя бы один catch или finally, иначе это ошибка компиляции.
Допустимы комбинации try-catch, try-finally и try-catch-finally. Блок finally может быть и без catch.

5. Если исключение в блоке Try – Catch не поймано, означает ли это крах программы.
Можно ли написать программу, которая никогда аварийно не завершается?
Необработанное исключение не обязательно рушит программу в месте возникновения: 
среда выполнения идёт вверх по стеку вызовов в поисках подходящего catch. Если 
такого нет ни в одном вызывающем методе, процесс аварийно завершается (обычно с 
сообщением об ошибке и кодом завершения, отличным от нуля). Блоки finally при этом могут и не выполниться.

